#!/usr/bin/env python3
"""Read an ETABS model DIRECTLY from the .EDB through the ETABS API - no manual export, no printed report.

Runs on a Windows PC with ETABS (v18 or later) installed:
    pip install comtypes openpyxl ezdxf matplotlib
    python etabs_live.py --edb "D:\\Projects\\Tower\\Tower.EDB" --q-allow 200 --combos U1,U2 -o out
    python etabs_live.py --attach --q-allow 200 -o out          (use the model already open in ETABS)

What it does
  1. Starts ETABS (hidden) or attaches to the running instance, opens the .EDB, sets units to kN-m.
  2. Runs the analysis if results are missing (or always with --run).
  3. Reads the result tables through the API (DatabaseTables) and writes them to out/etabs_tables.xlsx:
       Joint Reactions (load patterns), Element Forces - Columns / Beams, Pier Forces (combinations).
  4. Finds the model text file ETABS writes next to the .EDB (.$et / .e2k). If none, it saves the model once so
     ETABS writes it (or tells you to tick the option / File > Export > .e2k once).
  5. Calls building_design.py with these files: designs and drawings exactly as from manual exports.
Use --no-design to stop after step 4 (just extract the data).

Notes
  * Nothing is modified in your .EDB except running the analysis (ETABS stores results beside the model) and, if
    needed, one Save to produce the text file. Use --no-save to forbid saving.
  * SAFE has a similar API (SAFE v20+); ADAPT has no public API - use its Excel exports.
  * Written against the documented CSI OAPI (ETABSv1). Field names of the tables come from ETABS itself, so the
    downstream readers match them by name, not by position.
"""
import argparse
import glob
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

KN_M_C = 6  # eUnits.kN_m_C

TABLES = {
    "Joint Reactions": "patterns",
    "Element Forces - Columns": "combos",
    "Element Forces - Beams": "combos",
    "Pier Forces": "combos",
}


def connect(edb, attach, visible):
    try:
        import comtypes.client
    except ImportError:
        sys.exit("pip install comtypes  (Windows only)")
    helper = comtypes.client.CreateObject("ETABSv1.Helper")
    import comtypes.gen.ETABSv1 as E  # generated by the line above
    helper = helper.QueryInterface(E.cHelper)
    if attach:
        try:
            obj = helper.GetObject("CSI.ETABS.API.ETABSObject")
        except Exception:
            sys.exit("No running ETABS found to attach to. Open the model in ETABS or use --edb.")
        model = obj.SapModel
        started = False
    else:
        obj = helper.CreateObjectProgID("CSI.ETABS.API.ETABSObject")
        obj.ApplicationStart()
        if not visible:
            try:
                obj.Hide()
            except Exception:
                pass
        model = obj.SapModel
        model.InitializeNewModel()
        ret = model.File.OpenFile(os.path.abspath(edb))
        if ret != 0:
            obj.ApplicationExit(False)
            sys.exit(f"ETABS could not open {edb} (return code {ret}).")
        started = True
    model.SetPresentUnits(KN_M_C)
    return obj, model, started


def names(fn):
    """CSI 'GetNameList' style call -> list of names (robust to comtypes return shapes)."""
    r = fn()
    for part in r if isinstance(r, (list, tuple)) else []:
        if isinstance(part, (list, tuple)) and (not part or isinstance(part[0], str)):
            return list(part)
    return []


def has_results(model):
    try:
        return any(s == 4 for s in model.Analyze.GetCaseStatus()[2])  # (n, names, status, ret); 4 = finished
    except Exception:
        return False


def get_table(model, key, cases=None, combos=None):
    """Return (fields, rows) from DatabaseTables.GetTableForDisplayArray."""
    DT = model.DatabaseTables
    try:
        if cases is not None:
            DT.SetLoadCasesSelectedForDisplay(cases)
        if combos is not None:
            DT.SetLoadCombinationsSelectedForDisplay(combos)
    except Exception:
        pass
    r = DT.GetTableForDisplayArray(key, [], "All", 0, [], 0, [])
    # documented outputs: FieldKeyList, TableVersion, FieldsKeysIncluded, NumberRecords, TableData, ret
    r = list(r)
    ret = r[-1]
    if ret != 0:
        return None, None
    fields = data = None
    nrec = None
    for part in r[:-1]:
        if isinstance(part, int):
            nrec = part if nrec is None or part > 1 else nrec
    lists = [p for p in r[:-1] if isinstance(p, (list, tuple))]
    if len(lists) >= 2:
        fields, data = list(lists[-2]), list(lists[-1])
    if not fields or not data:
        return fields or [], []
    n = len(fields)
    rows = [data[i:i + n] for i in range(0, len(data), n)]
    return fields, rows


def write_xlsx(tables, path):
    import openpyxl
    wb = openpyxl.Workbook()
    wb.remove(wb.active)
    for key, (fields, rows) in tables.items():
        ws = wb.create_sheet(key[:31])
        ws.append([f"TABLE:  {key}"])
        ws.append(fields)
        for r in rows:
            ws.append([_num(v) for v in r])
    wb.save(path)


def _num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return v


def model_text_file(edb, model, allow_save):
    base = os.path.splitext(os.path.abspath(edb))[0] if edb else None
    if base is None:
        try:
            base = os.path.splitext(model.GetModelFilename(True))[0]
        except Exception:
            base = None
    def find():
        if not base:
            return None
        c = [base + ext for ext in (".$et", ".$ET", ".e2k", ".E2K") if os.path.exists(base + ext)]
        return max(c, key=os.path.getmtime) if c else None
    f = find()
    if f is None and allow_save:
        try:
            model.File.Save()
        except Exception:
            pass
        f = find()
    return f


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--edb", help="path to the .EDB model")
    g.add_argument("--attach", action="store_true", help="use the model open in a running ETABS")
    p.add_argument("--run", action="store_true", help="always re-run the analysis")
    p.add_argument("--visible", action="store_true")
    p.add_argument("--no-save", action="store_true")
    p.add_argument("--no-design", action="store_true")
    p.add_argument("--combos", help="ultimate combinations for members (default: all combinations)")
    p.add_argument("-o", "--out", required=True)
    a, rest = p.parse_known_args()  # everything else goes to building_design.py (--q-allow, --fcu, --project ...)
    os.makedirs(a.out, exist_ok=True)

    obj, model, started = connect(a.edb, a.attach, a.visible)
    try:
        if a.run or not has_results(model):
            print("Running analysis ...")
            model.Analyze.RunAnalysis()
        patterns = names(model.LoadPatterns.GetNameList)
        combos = names(model.RespCombo.GetNameList)
        use_combos = a.combos.split(",") if a.combos else combos
        print(f"Load patterns: {', '.join(patterns)}")
        print(f"Combinations: {', '.join(combos)}  (members designed for: {', '.join(use_combos)})")
        tables = {}
        for key, sel in TABLES.items():
            if sel == "patterns":
                f, rows = get_table(model, key, cases=patterns, combos=[])
            else:
                f, rows = get_table(model, key, cases=[], combos=use_combos)
            if f is None:
                print(f"  {key}: not available in this model")
                continue
            tables[key] = (f, rows)
            print(f"  {key}: {len(rows)} rows")
        xlsx = os.path.join(a.out, "etabs_tables.xlsx")
        write_xlsx(tables, xlsx)
        print(f"Tables written to {xlsx}")
        txt = model_text_file(a.edb, model, not a.no_save)
    finally:
        if started:
            obj.ApplicationExit(False)
    if not txt:
        sys.exit("ETABS did not leave a .$et/.e2k text file beside the model. In ETABS: File > Export > ETABS .e2k "
                 "Text File once (same folder, same name), then run this again.")
    print(f"Model text file: {txt}")
    if a.no_design:
        return
    cmd = [sys.executable, os.path.join(HERE, "building_design.py"), "--model", txt, "--reactions", xlsx,
           "--forces", xlsx, "-o", a.out] + (["--combos", ",".join(use_combos)] if use_combos else []) + rest
    print("Designing:", " ".join(f'"{c}"' if " " in c else c for c in cmd))
    sys.exit(subprocess.call(cmd))


if __name__ == "__main__":
    main()
